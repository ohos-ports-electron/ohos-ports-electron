import argparse,hashlib,json,subprocess
from pathlib import Path
p=argparse.ArgumentParser(description=__doc__);p.add_argument('--ndk',type=Path,required=True);p.add_argument('--output',type=Path,required=True);a=p.parse_args()
root=Path(__file__).resolve().parents[1];include=root/'shim/include';locked=json.loads((root/'shim/headers.lock.json').read_text())
for name,expected in locked.items():
 assert hashlib.sha256((include/name).read_bytes()).hexdigest()==expected,name
command=[str(a.ndk/'llvm/bin/clang'),'--target=aarch64-linux-ohos','--sysroot='+str(a.ndk/'sysroot'),'-x','c','-DNAPI_VERSION=10','-Xclang','-ast-dump=json','-fsyntax-only',str(include/'electron_node/src/node_api.h')]
ast=json.loads(subprocess.check_output(command));functions={}
def visit(n):
 if n.get('kind')=='FunctionDecl' and n.get('name','').startswith(('napi_','node_api_')):
  name=n['name'];types=[x['type']['qualType'] for x in n.get('inner',[]) if x['kind']=='ParmVarDecl'];ret=n['type']['qualType'].split(' (',1)[0]
  assert all('(' not in t and '[' not in t for t in types),name
  functions[name]=(ret,types)
 for child in n.get('inner',[]):visit(child)
visit(ast)
head=r'''// Generated by generate-shim.py; SPDX-License-Identifier: MIT
#define _GNU_SOURCE 1
#define HIDE_NAPI_AND_UV 1
#define NAPI_VERSION 10
#include "node_api.h"
#include <dlfcn.h>
#include <pthread.h>
#include <stdatomic.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
static pthread_once_t canvas_shim_once = PTHREAD_ONCE_INIT;
static void *canvas_electron_handle;
static void canvas_shim_open(void) {
  canvas_electron_handle = dlopen("libelectron.so", RTLD_NOW | RTLD_LOCAL);
  if (!canvas_electron_handle) {
    fprintf(stderr, "canvas shim: cannot open libelectron.so: %s\n", dlerror());
    abort();
  }
}
static void *canvas_shim_resolve(const char *name) {
  if (pthread_once(&canvas_shim_once, canvas_shim_open) != 0) abort();
  void *symbol = dlsym(canvas_electron_handle, name);
  Dl_info location;
  if (!symbol || !dladdr(symbol, &location) || !location.dli_fname) {
    fprintf(stderr, "canvas shim: required Electron symbol missing: %s\n", name);
    abort();
  }
  const char *base = strrchr(location.dli_fname, '/');
  base = base ? base + 1 : location.dli_fname;
  if (strcmp(base, "libelectron.so") != 0) {
    fprintf(stderr, "canvas shim: refusing non-Electron provider for %s: %s\n", name, location.dli_fname);
    abort();
  }
  return symbol;
}
'''
rows=[head]
for name,(ret,types) in sorted(functions.items()):
 params=', '.join(f'{t} a{i}' for i,t in enumerate(types)) or 'void';signature=', '.join(types) or 'void';args=', '.join(f'a{i}' for i in range(len(types)))
 rows += [f'\n{ret} {name}({params}) {{',f'  typedef {ret} (*target_fn)({signature});','  static _Atomic(void *) cached = NULL;','  void *address = atomic_load_explicit(&cached, memory_order_acquire);',f'  if (!address) {{ address = canvas_shim_resolve("{name}"); atomic_store_explicit(&cached, address, memory_order_release); }}',f'  {"return " if ret != "void" else ""}((target_fn)address)({args});']
 if name=='napi_fatal_error':rows.append('  abort();')
 rows.append('}')
a.output.parent.mkdir(parents=True,exist_ok=True);a.output.write_text('\n'.join(rows)+'\n');a.output.with_suffix('.json').write_text(json.dumps({'functions':sorted(functions),'sourceSha256':hashlib.sha256(a.output.read_bytes()).hexdigest(),'implementation':'project source; typed header-derived wrappers; not official binary reconstruction'},indent=2)+'\n')
print(json.dumps({'functions':len(functions),'source':str(a.output)}))
